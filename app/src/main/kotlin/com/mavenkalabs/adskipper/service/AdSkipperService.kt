@SuppressLint("AccessibilityPolicy")
class AdSkipperService : AccessibilityService() {
    private var muteAds = false

    private var adInProgress = false

    private val configReader: ConfigReader? = null

    /**
     * Last time a click happened
     */
    private var lastClickTS = 0L

    /**
     * Last time app itself tapped on a widget
     */
    private var lastAppClickTS = 0L

    private val listenerRef = AtomicReference<OnSharedPreferenceChangeListener?>()

    private val packageClickRules = AtomicReference<MutableMap<String, BaseRule>?>()

    private val packageMuteRules = AtomicReference<MutableMap<String, BaseRule>?>()

    private val serviceJob = SupervisorJob()
    private val serviceScope = CoroutineScope(Dispatchers.Main + serviceJob)
    private var syncJob: Job? = null

    override fun onAccessibilityEvent(event: AccessibilityEvent) {
        try {
            if (event.eventType == AccessibilityEvent.TYPE_VIEW_CLICKED) {
                val now = System.currentTimeMillis()
                // ignore click events generated by app itself
                if ((now - lastAppClickTS) > APP_CLICK_QUIET_INTERVAL) {
                    lastClickTS = System.currentTimeMillis()
                }
                return
            }

            val parameters = mutableMapOf(
                RULE_PARAM_LAST_USER_CLICK_TS to lastClickTS
            )

            val eventPkgName =
                (if (event.packageName != null) event.packageName.toString() else null)
            val rootNode = rootInActiveWindow
            val currentMuteRules = packageMuteRules.get()!![eventPkgName]
            if (rootNode != null && currentMuteRules != null) {
                val conditionSatisfied = currentMuteRules.apply(rootNode, parameters).isPassed
                if (conditionSatisfied) {
                    if (muteAds && !adInProgress) {
                        toggleMute(true)
                        adInProgress = true
                        AppLog.d(TAG, "onAccessibilityEvent: Detected ad")
                        AppLog.logAccessibilityEvent(rootInActiveWindow, AppLog.EventType.AD)
                    }
                }

                if (muteAds && !conditionSatisfied) {
                    if (adInProgress) {
                        toggleMute(false)
                        adInProgress = false
                    }
                }
            }

            val currentClickRules = packageClickRules.get()!![eventPkgName]
            if (rootNode != null && currentClickRules != null) {
                val result = currentClickRules.apply(rootNode, parameters)

                val conditionSatisfied = result.isPassed
                val foundNodes = result.filteredNodes
                if (conditionSatisfied && !foundNodes.isNullOrEmpty()) {
                    foundNodes.stream()
                        .filter { it.isEnabled }
                        .findFirst()
                        .ifPresent(Consumer { accessibilityNodeInfo: AccessibilityNodeInfo ->
                            var clickableNode: AccessibilityNodeInfo? = accessibilityNodeInfo
                            while(clickableNode != null && !clickableNode.isClickable) {
                                clickableNode = clickableNode.parent
                            }
                            if (clickableNode != null) {
                                tap(clickableNode)
                                AppLog.d(
                                    TAG,
                                    "onAccessibilityEvent: Skipped ad {0}",
                                    clickableNode
                                )
                                AppLog.logAccessibilityEvent(
                                    rootInActiveWindow,
                                    AppLog.EventType.SKIP
                                )
                            }
                        })
                }
            }
        } catch (e: Exception) {
            AppLog.e(TAG, "Unexpected error", e)
        }
    }

    private fun performSwipe(up: Boolean = false) {
        val windowManager = getSystemService(WINDOW_SERVICE) as WindowManager

        val screenWidth: Int
        val screenHeight: Int

        // 1. Resolve screen metrics safely across varying Android SDK baselines
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            val windowMetrics: WindowMetrics = windowManager.currentWindowMetrics
            val bounds: Rect = windowMetrics.bounds
            screenWidth = bounds.width()
            screenHeight = bounds.height()
        } else {
            // Legacy metric gathering fallback for older engine baselines
            val displayMetrics = android.util.DisplayMetrics()
            @Suppress("DEPRECATION")
            windowManager.defaultDisplay.getRealMetrics(displayMetrics)
            screenWidth = displayMetrics.widthPixels
            screenHeight = displayMetrics.heightPixels
        }
        // 1. Establish structural coordinates based on screen bounds
        val startX = screenWidth / 2f
        val startY = if (up) screenHeight * 0.8f else screenHeight * 0.2f // Start 80% down the screen
        val endX = screenWidth / 2f
        val endY = if (up) screenHeight * 0.2f else screenHeight * 0.8f   // End 20% down from the top

        // 2. Map out the linear trajectory path
        val swipePath = Path().apply {
            moveTo(startX, startY)
            lineTo(endX, endY)
        }

        /*
         * 3. Construct the Gesture Stroke
         * Parameter 1: The drawn path trajectory
         * Parameter 2: Start delay in milliseconds (0 means execute instantly)
         * Parameter 3: Stroke duration in milliseconds (300ms is standard for a quick swipe)
         */
        val strokeDescription = StrokeDescription(swipePath, 0, 300)

        // 4. Build the immutable gesture manifest
        val gestureBuilder = GestureDescription.Builder().apply {
            addStroke(strokeDescription)
        }
        val gestureDescription = gestureBuilder.build()

        // 5. Fire the gesture down into the active window pipeline
        dispatchGesture(gestureDescription, null, null) // Passing null uses the main system worker thread
    }

    private fun tap(node: AccessibilityNodeInfo) {
        lastAppClickTS = System.currentTimeMillis()

        val success = node.performAction(AccessibilityNodeInfo.ACTION_CLICK)

        // try click action if gesture doesn't succeed
        if (!success) {
            AppLog.d(TAG, "performAction didn't work. Using click gesture")

            val nodeBounds = Rect()
            node.getBoundsInScreen(nodeBounds)
            val tapPath = Path()
            tapPath.moveTo(nodeBounds.centerX().toFloat(), nodeBounds.centerY().toFloat())
            val tapStroke =
                StrokeDescription(tapPath, 0, ViewConfiguration.getTapTimeout().toLong())

            val gestureBuilder = GestureDescription.Builder()
            gestureBuilder.addStroke(tapStroke)
            dispatchGesture(gestureBuilder.build(), null, null)
        }
    }

    private fun toggleMute(mute: Boolean) {
        val audioManager = getSystemService(AUDIO_SERVICE) as AudioManager
        val isCurrentlyMuted = audioManager.isStreamMute(AudioManager.STREAM_MUSIC)
        if (isCurrentlyMuted != mute) {
            audioManager.adjustStreamVolume(
                AudioManager.STREAM_MUSIC,
                if (mute) AudioManager.ADJUST_MUTE else AudioManager.ADJUST_UNMUTE, 0
            )
        }
        if (mute) {
            AppLog.d(TAG, "Toggling mute to true")
        } else {
            AppLog.d(TAG, "Toggling mute to false")
        }
    }

    override fun onUnbind(intent: Intent?): Boolean {
        toggleMute(false)
        return true
    }

    override fun onInterrupt() {
        toggleMute(false)
    }

    override fun onDestroy() {
        super.onDestroy()

        if (configReader != null) {
            try {
                configReader.close()
            } catch (e: Exception) {
                AppLog.e(TAG, e.message!!, e)
            }
        }

        serviceJob.cancelChildren()
    }

    public override fun onServiceConnected() {
        val prefs = PreferenceManager.getDefaultSharedPreferences(applicationContext)
        muteAds = prefs.getBoolean(getString(R.string.pref_key_mute_ads), true)
        if (prefs.getBoolean(getString(R.string.pref_key_enable_logging), false)) AppLog.enable() else AppLog.disable()

        val listener: OnSharedPreferenceChangeListener?
        prefs.registerOnSharedPreferenceChangeListener(OnSharedPreferenceChangeListener { p: SharedPreferences?, key: String? ->
            AppLog.d(TAG, "onServiceConnected: pref changed {0}", key)
            when (key) {
                getString(R.string.pref_key_mute_ads) -> {
                    muteAds = p!!.getBoolean(key, false)
                    AppLog.d(TAG, "onServiceConnected: muteAds now {0}", muteAds)
                }
                getString(R.string.pref_key_pro_enable_voice) -> {
                    val voiceEnabled = p!!.getBoolean(key, false)
                    if (voiceEnabled) {
                        syncJob = serviceScope.launch {
                            val success = prepareVoiceInteractionEngine()
                            if (!success) {
                                Toast.makeText(this@AdSkipperService, R.string.error_init_voice, Toast.LENGTH_SHORT).show()
                                val prefs = PreferenceManager.getDefaultSharedPreferences(applicationContext)
                                prefs.edit(commit = true) {
                                    putBoolean(
                                        getString(R.string.pref_key_pro_enable_voice),
                                        false
                                    )
                                }
                            }
                        }
                    } else {
                        syncJob?.cancel()
                        stopVoiceInteractionEngine()
                    }
                }
            }
        }.also { listener = it })
        listenerRef.set(listener)

        val rulesParser = RulesParser()
        packageClickRules.set(
            mutableMapOf(
                "com.google.android.youtube" to
                    rulesParser.orRules(
                        *listOf(
                            "skip_ad_button",
                            "modern_miniplayer_skip_ad_button",
                            "overflow_button&expanded_cta_buttons&!player_learn_more_button",
                            "list_item_text[1]&_ruleid_no_recent_user_click,2000"
                        ).map
                        { rulesParser.parse(it, "com.google.android.youtube") }
                            .toTypedArray()),
                "com.google.android.apps.youtube.music" to
                    rulesParser.orRules(
                        *listOf(
                            "skip_ad_button",
                            "snackbar_action&_ruleid_no_recent_user_click,10000"
                        ).map
                        {
                            rulesParser.parse(
                                it,
                                "com.google.android.apps.youtube.music"
                            )
                        }.toTypedArray())
            )
        )

        packageMuteRules.set(
            mutableMapOf(
                "com.google.android.youtube" to
                    rulesParser.orRules(
                        *listOf(
                            "player_learn_more_button",
                            "ad_progress_text",
                            "modern_miniplayer_ad_badge",
                            "ad_badge&!collapsible_ad_cta_overlay_container"
                        ).map
                        { rulesParser.parse(it, "com.google.android.youtube") }
                            .toTypedArray()),
                "com.google.android.apps.youtube.music" to
                    rulesParser.orRules(
                        *listOf(
                            "player_learn_more_button",
                            "ad_progress_text"
                        ).map
                        {
                            rulesParser.parse(
                                it,
                                "com.google.android.apps.youtube.music"
                            )
                        }.toTypedArray())
            )
        )
    }


    private fun stopVoiceInteractionEngine() {
        VoiceCommandManager.stopEngine()
    }

    private suspend fun prepareVoiceInteractionEngine() : Boolean =
        withContext(Dispatchers.IO) {
            var success = false
            val voiceModel = VoiceModelManager.getOrFetchModel(this@AdSkipperService)
            if (voiceModel != null) {
                try {
                    VoiceCommandManager.startEngine(voiceModel) { when(it) {
                        VoiceCommand.SWIPE_UP -> performSwipe(true)
                        VoiceCommand.SWIPE_DOWN -> performSwipe(false)
                    } }
                    success = true
                } catch (_ : SecurityException) {
                    // do nothing
                }
            }

            return@withContext success
        }


    companion object {
        const val APP_CLICK_QUIET_INTERVAL: Int = 1000

        private val TAG: String = AdSkipperService::class.java.getName()
    }
}
